"""Regenerate contracts/camconfig_schema.sql and contracts/camconfig_vectors.json.

Both files are copied verbatim into cams-detect (contracts/), which reads cams_config without owning it:
its tests build the schema from the .sql file and check its reader against the vectors.
tests/test_contracts.py fails while these files are out of date.

    python scripts/gen_camconfig_contracts.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cams_record.camconfig.model import CameraObject, Stream  # noqa: E402
from cams_record.camconfig.schema import MIGRATIONS  # noqa: E402
from cams_record.camconfig.views import detect_camera  # noqa: E402


def schema_sql() -> str:
    out = ["-- Generated by scripts/gen_camconfig_contracts.py from cams_record/camconfig/schema.py.",
           "-- cams-record owns this schema; do not edit copies.", ""]
    for version, stmts in MIGRATIONS:
        out.append(f"-- v{version}")
        out.extend(stmt.strip() + ";" for stmt in stmts)
        out.append("")
    return "\n".join(out)


def _cam(cid, **kw):
    base = {"id": cid, "name": cid.replace("-", " ").title(), "visibility": "everyone",
            "streams": {"main": Stream("main", f"{cid}-main"), "sub": Stream("sub", cid)},
            "use": {"live": ("sub",), "detect": ("sub",), "verify": ("main",), "record": ("main", "sub")}}
    base.update(kw)
    return CameraObject(**base)


CASES = [
    ("typical", _cam("front-door", detection={
        "enabled": True, "decode_fps": 3, "hires_snapshot": True, "motion": {"threshold": 25},
        "zones": {"porch": [[0.0, 0.5], [1.0, 0.5], [1.0, 1.0], [0.0, 1.0]]}, "required_zones": ["porch"],
        "classes": {"person": {"min_score": 0.6}, "car": False}})),
    ("detection switched off", _cam("back-yard", detection={"enabled": False})),
    ("camera disabled overrides detection", _cam("garage", enabled=False, detection={"enabled": True})),
    ("not set up for detection", _cam("driveway", detection=None)),
    ("detection settings but no detect stream",
     _cam("shed", detection={"enabled": True}, use={"live": ("sub",), "record": ("main",)})),
    ("no verify stream", _cam("porch", detection={}, use={"live": ("sub",), "detect": ("sub",)})),
    ("detects on main, verifies on main", _cam("gate", detection={"decode_fps": 2},
                                                use={"detect": ("main",), "verify": ("main",)})),
    ("stray stream keys in settings are ignored", _cam("side", detection={
        "name": "Old", "stream": "old", "main_stream": "old-main", "width": 480})),
    ("single stream, extra snapshot stream", _cam("attic", streams={
        "main": Stream("main", "attic"), "snap": Stream("snap", "attic-snap")},
        use={"detect": ("main",), "snapshot": ("snap",)}, detection={"classes": ["person"]})),
]


def vectors() -> dict:
    return {
        "_comment": "Generated by cams-record scripts/gen_camconfig_contracts.py. Each case: a camera object "
                    "(cams_config row data, as CameraObject.to_dict) and the cameras.yaml entry cams-detect "
                    "must derive from it (null = not a cams-detect camera).",
        "cases": [{"case": name, "object": cam.to_dict(), "detect": detect_camera(cam)} for name, cam in CASES],
    }


def render() -> dict[str, str]:
    return {"contracts/camconfig_schema.sql": schema_sql(),
            "contracts/camconfig_vectors.json": json.dumps(vectors(), indent=2, sort_keys=True) + "\n"}


if __name__ == "__main__":
    for rel, text in render().items():
        (ROOT / rel).write_text(text, encoding="utf-8")
        print(f"wrote {rel}")
